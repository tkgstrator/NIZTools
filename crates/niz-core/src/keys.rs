pub fn key_name(code: u8) -> &'static str {
    match code {
        199 => "Mouse double-click",
        200 => "Delay marker (macros only)",
        _ => KEY_NAMES
            .get(code as usize)
            .copied()
            .unwrap_or("Reserved code"),
    }
}

pub fn parse_key(text: &str) -> Result<u8> {
    let value = text.split(" · ").next().unwrap_or(text).trim();
    if let Some(code) = value.strip_prefix('#') {
        return code
            .parse::<u8>()
            .map_err(|_| Error::Invalid("key number must be 0..255".into()));
    }
    if value
        .get(..2)
        .is_some_and(|prefix| prefix.eq_ignore_ascii_case("0x"))
    {
        return u8::from_str_radix(&value[2..], 16)
            .map_err(|_| Error::Invalid("hex key must be 0x00..0xff".into()));
    }
    if let Some(code) = (0..=255u8).find(|&code| {
        key_name(code) != "Reserved code" && key_name(code).eq_ignore_ascii_case(value)
    }) {
        return Ok(code);
    }
    let compact = value.to_ascii_lowercase().replace([' ', '-'], "");
    let code = match compact.as_str() {
        "none" | "noaction" => 0,
        "escape" => 1,
        "enter" | "ret" => 54,
        "bs" => 27,
        "caps" | "capslock" => 42,
        "shift" | "lshift" => 55,
        "rshift" => 66,
        "ctrl" | "control" | "lctrl" => 67,
        "rctrl" => 74,
        "cmd" | "command" | "lcmd" | "lwin" => 68,
        "rcmd" | "rwin" => 72,
        "alt" | "option" | "lalt" => 69,
        "ralt" => 71,
        "lfn" => 166,
        "rfn" => 156,
        "↑" | "up" | "arrowup" | "uparrow" => 87,
        "←" | "left" | "arrowleft" | "leftarrow" => 88,
        "↓" | "down" | "arrowdown" | "downarrow" => 89,
        "→" | "right" | "arrowright" | "rightarrow" => 90,
        "pgup" => 83,
        "pgdn" => 86,
        "prisc" | "printscreen" => 78,
        "scllk" | "scrolllock" => 79,
        "mousekeyleft" => 130,
        "mousekeyright" => 131,
        "mousekeymiddle" => 132,
        "mousewheelup" => 133,
        "mousewheeldn" => 134,
        "adjusttriggerpoint" => 149,
        "programmablekeyboard" => 159,
        "medianext" => 108,
        "mediaprevious" => 109,
        "mediastop" => 110,
        "mediaplay/pause" => 111,
        "mediamute" => 112,
        "mediavolumeup" => 113,
        "mediavolumedown" => 114,
        "backlightswitch" => 135,
        _ => return Err(Error::Invalid(format!("unknown key name {value:?}"))),
    };
    Ok(code)
}

